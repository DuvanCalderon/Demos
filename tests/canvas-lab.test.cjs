const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {JSDOM,VirtualConsole}=require('jsdom');
const root=path.resolve(__dirname,'..');
const labDir=path.join(root,'Proyectos-de-ingenieria','Modelo-Canvas-Lab');
const html=fs.readFileSync(path.join(labDir,'index.html'),'utf8');
const index=fs.readFileSync(path.join(root,'index.html'),'utf8');
const pdf=fs.readFileSync(path.join(labDir,'Modelo-Canvas.pdf'));
assert.equal(pdf.toString('ascii',0,5),'%PDF-','El material original debe ser un PDF real');
const cardCount=(index.match(/<article class="lab-card"/g)||[]).length;
assert.ok(cardCount>=38,'El catálogo debe conservar sus tarjetas');
assert.match(index,new RegExp('Todos <span>'+cardCount+'</span>'),'El contador general debe coincidir con las tarjetas');
assert.match(index,/Canvas Lab · Modelo de negocio/,'Debe existir la tarjeta Canvas Lab');
const engineeringCount=(index.match(/data-category="Proyectos de ingeniería"/g)||[]).length;
assert.match(index,new RegExp('data-filter="Proyectos de ingeniería"[^>]+>🏗️ Proyectos de ingeniería <span>'+engineeringCount+'</span>'),'El filtro debe contar los demos de ingeniería');
assert.match(index,/href="\.\/Proyectos-de-ingenieria\/Modelo-Canvas-Lab\/"/,'La tarjeta debe enlazar el demo');
assert.match(html,/href="\.\/Modelo-Canvas\.pdf"/,'El PDF debe descargarse desde la carpeta del demo');
assert.equal((html.match(/\{t:'/g)||[]).length,15,'El laboratorio debe tener quince desafíos');
const inline=[...html.matchAll(/<script[^>]*>([\s\S]*?)<\/script>/gi)].map(m=>m[1]);
assert.equal(inline.length,1,'Debe existir un script autosuficiente sin dependencias');
new (require('node:vm').Script)(inline[0],{filename:'canvas-lab-inline.js'});
const failures=[];
const vc=new VirtualConsole();
vc.on('jsdomError',e=>failures.push(e.message));
let downloads=0,prints=0;
const dom=new JSDOM(html,{url:'https://duvancalderon.github.io/Demos/Proyectos-de-ingenieria/Modelo-Canvas-Lab/',runScripts:'dangerously',pretendToBeVisual:true,virtualConsole:vc,beforeParse(win){win.scrollTo=function(){};win.confirm=function(){return true};win.print=function(){prints++};win.URL.createObjectURL=function(){return 'blob:canvas-test'};win.URL.revokeObjectURL=function(){};win.HTMLAnchorElement.prototype.click=function(){downloads++}}});
const d=dom.window.document;
const click=q=>{const el=d.querySelector(q);assert.ok(el,'No se encontró: '+q);el.click();return el};
const txt=q=>{const el=d.querySelector(q);assert.ok(el);return el.textContent.trim()};
function emit(el,name){el.dispatchEvent(new dom.window.Event(name,{bubbles:true}))}
assert.equal(d.querySelectorAll('.block').length,9,'Nueve bloques interactivos');
assert.equal(d.querySelectorAll('.field textarea').length,9,'Nueve campos editables');
assert.equal(d.querySelectorAll('.view').length,5,'Cinco secciones');
const ids=[...d.querySelectorAll('[id]')].map(e=>e.id);
assert.equal(new Set(ids).size,ids.length,'No debe haber IDs duplicados');
click('.block[data-id="channels"]');
assert.equal(txt('#def-title'),'Canales de distribución','El mapa debe actualizar la explicación del bloque');
click('#to-builder');
assert.ok(d.querySelector('#construir').classList.contains('active'),'Botón aplicar debe navegar al constructor');
click('#load-helmet');
assert.equal(txt('#builder-count'),'9/9','El ejemplo debe llenar los nueve campos');
const area=d.querySelector('#field-value');
assert.ok(area.value.includes('Sanitizar'),'El ejemplo debe tener propuesta de valor');
area.value='Nueva propuesta de valor';
emit(area,'input');
const saved=JSON.parse(dom.window.localStorage.getItem('canvas-lab-unal-v1'));
assert.equal(saved.model.value,'Nueva propuesta de valor','Editar debe guardar en localStorage');
click('#export-json');
assert.ok(downloads>=1,'Exportar JSON debe iniciar una descarga');
click('#print-model');
assert.equal(prints,1,'Imprimir debe funcionar');
click('.tab[data-view="practicar"]');
assert.ok(d.querySelector('#practicar').classList.contains('active'));
assert.ok(txt('#quiz-question').includes('motociclistas'));
click('.choice[data-choice="segments"]');
click('#quiz-check');
assert.match(txt('#quiz-feedback'),/Correcto/,'La respuesta acertada debe recibir confirmación');
assert.equal(txt('#quiz-score'),'1');
click('#quiz-next');
click('#quiz-hint');
assert.match(txt('#quiz-feedback'),/Pista/,'La pista debe mostrarse al solicitarla');
click('.choice[data-choice="costs"]');
click('#quiz-check');
assert.equal(txt('#quiz-score'),'1','Una respuesta equivocada no suma puntos');
click('.choice[data-choice="value"]');
click('#quiz-check');
assert.equal(txt('#quiz-score'),'2');
click('[data-level="2"]');
click('#quiz-solution');
assert.match(txt('#quiz-feedback'),/Solución/,'La respuesta puede revelarse');
assert.equal(txt('#quiz-score'),'2','Revelar no suma puntos');
click('#quiz-reset');
assert.equal(txt('#quiz-score'),'0','Se puede reiniciar el cuestionario');
assert.equal(txt('#builder-count'),'9/9','Reiniciar retos debe conservar el modelo');
click('.tab[data-view="simular"]');
const model=d.querySelector('#sim-type');
model.value='freemium';emit(model,'change');
assert.match(txt('#sim-context'),/Freemium/,'El simulador debe cambiar de modelo');
const before=txt('#m-revenue');
const users=d.querySelector('#sim-users');users.value='4000';emit(users,'input');
assert.notEqual(txt('#m-revenue'),before,'Mover un deslizador debe cambiar los ingresos');
const price=d.querySelector('#sim-price'),variable=d.querySelector('#sim-variable');
price.value='1000';variable.value='70000';emit(price,'input');
assert.match(txt('#sim-feedback'),/NO cubre su costo variable/,'Margen negativo debe tener alerta');
click('#sim-reset');
assert.equal(price.value,'34000','Restablecer debe restaurar el escenario seleccionado');
click('.tab[data-view="construir"]');
click('#clear-model');
assert.equal(txt('#builder-count'),'0/9','Vaciar debe borrar los nueve campos');
click('.tab[data-view="recursos"]');
assert.ok(d.querySelector('#pdf-download').getAttribute('href').endsWith('Modelo-Canvas.pdf'));
click('#reset-all');
assert.equal(txt('#quiz-score'),'0');
assert.equal(txt('#builder-count'),'0/9');
assert.deepEqual(failures,[],'No debe haber errores de ejecución');
console.log('OK: Canvas Lab (9 bloques, 15 retos, navegación, validación, progreso, guardado, ejemplos, exportación, impresión, simulador, PDF, reinicio y catálogo).');
dom.window.close();
